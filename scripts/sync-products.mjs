// Genera SQL idempotente que sincroniza public.products con el catálogo
// estático (data/menu.js). Los identificadores son los mismos que produce
// createBilingualMenuCatalog. No usa credenciales: el SQL se versiona como
// migración y se aplica con el flujo habitual de Supabase.
//
// Uso:
//   npx supabase migration new sync_products
//   node scripts/sync-products.mjs --out supabase/migrations/<archivo>.sql
//
// La sincronización actualiza nombre, categoría, precio y orden; marca
// in_catalog = false en productos retirados y nunca modifica is_available.

import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { MENU_CATALOG } from '../data/menu.js';

export const PRODUCT_SYNC_MARKER = '-- generated by scripts/sync-products.mjs';
export const DEFAULT_BUSINESS_NAME = 'Cafetería Spirit - Montcada';

export function parsePriceCents(price) {
  const value = String(price ?? '').trim();
  if (value === '') return null;
  const match = /^(\d{1,4}),(\d{2}) €$/.exec(value);
  if (!match) throw new Error(`Precio con formato no reconocido: "${value}"`);
  return Number(match[1]) * 100 + Number(match[2]);
}

export function buildProductRows(catalog = MENU_CATALOG) {
  const rows = [];
  const skipped = [];

  catalog.es.forEach((category, categoryIndex) => {
    const catalanCategory = catalog.ca[categoryIndex];
    category.products.forEach((product, productIndex) => {
      const catalanProduct = catalanCategory.products[productIndex];
      if (catalanProduct.id !== product.id) {
        throw new Error(`Catálogo desalineado en ${product.id}`);
      }
      const priceCents = parsePriceCents(product.price);
      if (priceCents === null) {
        skipped.push(product.id);
        return;
      }
      rows.push({
        id: product.id,
        categoryId: category.id,
        nameEs: product.name,
        nameCa: catalanProduct.name,
        priceCents,
        sortOrder: categoryIndex * 1000 + productIndex
      });
    });
  });

  return { rows, skipped };
}

const sqlText = (value) => `'${String(value).replaceAll("'", "''")}'`;

export function buildProductSyncSql({ rows, skipped }, businessName = DEFAULT_BUSINESS_NAME) {
  if (!rows.length) throw new Error('El catálogo no contiene productos con precio');

  const values = rows
    .map((row) => `    (v_business_id, ${sqlText(row.id)}, ${sqlText(row.categoryId)}, ${sqlText(row.nameEs)}, ${sqlText(row.nameCa)}, ${row.priceCents}, ${row.sortOrder})`)
    .join(',\n');
  const ids = rows.map((row) => sqlText(row.id)).join(', ');
  const skippedNote = skipped.length
    ? `-- Sin precio (no se pueden pedir): ${skipped.join(', ')}\n`
    : '';

  return `${PRODUCT_SYNC_MARKER}. No editar a mano.
${skippedNote}do $$
declare
  v_business_id uuid;
begin
  select business.id
  into v_business_id
  from public.businesses as business
  where lower(btrim(business.name)) = lower(btrim(${sqlText(businessName)}))
  limit 1;

  if v_business_id is null then
    raise exception 'product_sync_business_not_found';
  end if;

  insert into public.products (
    business_id, id, category_id, name_es, name_ca, price_cents, sort_order
  )
  values
${values}
  on conflict (business_id, id) do update
  set category_id = excluded.category_id,
      name_es = excluded.name_es,
      name_ca = excluded.name_ca,
      price_cents = excluded.price_cents,
      sort_order = excluded.sort_order,
      in_catalog = true;

  update public.products
  set in_catalog = false
  where business_id = v_business_id
    and in_catalog
    and id <> all (array[${ids}]::text[]);
end;
$$;
`;
}

async function main(argv) {
  const outIndex = argv.indexOf('--out');
  const businessIndex = argv.indexOf('--business');
  const businessName = businessIndex >= 0 ? argv[businessIndex + 1] : DEFAULT_BUSINESS_NAME;
  const sql = buildProductSyncSql(buildProductRows(), businessName);

  if (outIndex >= 0) {
    const target = argv[outIndex + 1];
    if (!target) throw new Error('Falta la ruta tras --out');
    await writeFile(target, sql);
    console.log(`SQL de productos escrito en ${target}`);
  } else {
    process.stdout.write(sql);
  }
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
